"""Backtest the models and write docs/evaluation.md.

Usage: python -m forecast.evaluate [--mlflow]
"""

import argparse
from datetime import date
from pathlib import Path

import pandas as pd

from forecast.backtest import run_backtest
from forecast.learned import GradientBoosting, HourlyRidge
from forecast.metrics import breakdown, summarize
from forecast.models import SeasonalNaive

# Fixed on 2026-11-26, before any model was trained.
BACKTEST = (date(2025, 9, 1), date(2026, 8, 31))
# Held out: used once, for the final model. Do not evaluate on it before then.
FINAL_TEST = (date(2026, 9, 1), date(2026, 11, 25))

# Declared before running them, so the comparison is not a long search over the backtest year.
MODELS = {
    "seasonal_naive": (SeasonalNaive, {}),
    "ridge_no_temperature": (HourlyRidge, {"use_temperature": False}),
    "ridge": (HourlyRidge, {}),
    "boosting_no_temperature": (GradientBoosting, {"use_temperature": False}),
    "boosting": (GradientBoosting, {}),
    "boosting_weekly_change": (GradientBoosting, {"predict_change": True}),
}
WEEKDAYS = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]


def markdown_table(table: pd.DataFrame, label: str, names: dict | None = None) -> str:
    lines = [f"| {label} | Hours | MAE (MW) | MAPE (%) |", "|---|---|---|---|"]
    for key, row in table.iterrows():
        name = names.get(key, key) if names else key
        lines.append(
            f"| {name} | {int(row['hours']):,} | {row['mae_mw']:,.0f} | {row['mape_pct']:.2f} |"
        )
    return "\n".join(lines)


def run_all(demand: pd.Series, temperature: pd.Series) -> dict[str, pd.DataFrame]:
    results = {}
    for name, (cls, params) in MODELS.items():
        results[name] = run_backtest(demand, temperature, cls(**params), *BACKTEST)
        print(f"{name}: MAPE {summarize(results[name])['mape_pct']:.2f}%", flush=True)
    return results


def log_to_mlflow(results: dict[str, pd.DataFrame]) -> None:
    import mlflow  # only needed with --mlflow

    mlflow.set_tracking_uri("sqlite:///mlflow.db")
    mlflow.set_experiment("day-ahead-demand")
    for name, table in results.items():
        with mlflow.start_run(run_name=name):
            mlflow.log_params(
                {"model": MODELS[name][0].__name__, **MODELS[name][1]}
                | {"backtest_first": BACKTEST[0], "backtest_last": BACKTEST[1]}
            )
            total = summarize(table)
            mlflow.log_metrics({k: float(v) for k, v in total.items()})


def report(results: dict[str, pd.DataFrame]) -> str:
    first, last = BACKTEST
    totals = {name: summarize(table) for name, table in results.items()}
    best = min(totals, key=lambda name: totals[name]["mape_pct"])
    parts = [
        "# Evaluation",
        "",
        "Generated by `python -m forecast.evaluate`. Do not edit by hand.",
        "",
        f"Backtest: every day from {first} to {last}, forecast issued at 10:00 Europe/Madrid on",
        "the day before, models refitted monthly. The period",
        f"{FINAL_TEST[0]} to {FINAL_TEST[1]} is held out and has not been evaluated.",
        "The 2025-04-28 blackout is outside both periods and is hidden from training and lags.",
        "",
        "## Models",
        "",
        "| Model | Hours | Skipped | MAE (MW) | MAPE (%) |",
        "|---|---|---|---|---|",
    ]
    for name, total in totals.items():
        parts.append(
            f"| {name} | {total['hours']:,} | {total['skipped']} | "
            f"{total['mae_mw']:,.0f} | {total['mape_pct']:.2f} |"
        )
    parts += [
        "",
        f"Lowest MAPE: **{best}**. Because it was picked on this backtest, its error here is a",
        "slightly optimistic estimate; the held-out period is the unbiased check.",
    ]
    names = ["seasonal_naive"] + ([best] if best != "seasonal_naive" else [])
    for name in names:
        table = results[name]
        parts += [
            "",
            f"## {name}",
            "",
            markdown_table(breakdown(table, "month"), "Month"),
            "",
            markdown_table(breakdown(table, "weekday"), "Weekday", dict(enumerate(WEEKDAYS))),
            "",
            markdown_table(
                breakdown(table, "holiday"), "National holiday", {False: "No", True: "Yes"}
            ),
            "",
            markdown_table(breakdown(table, "hour"), "Local hour"),
        ]
    return "\n".join(parts) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mlflow", action="store_true", help="also log the runs to mlflow.db")
    args = parser.parse_args()
    demand = pd.read_parquet("data/demand.parquet")["demand_mw"]
    temperature = pd.read_parquet("data/temperature.parquet")["temperature_c"]
    results = run_all(demand, temperature)
    if args.mlflow:
        log_to_mlflow(results)
    Path("docs/evaluation.md").write_text(report(results))


if __name__ == "__main__":
    main()
