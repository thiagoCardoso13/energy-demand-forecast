"""Backtest the models and write docs/evaluation.md.

Usage: python -m forecast.evaluate
"""

from datetime import date
from pathlib import Path

import pandas as pd

from forecast.backtest import run_backtest
from forecast.metrics import breakdown, summarize
from forecast.models import seasonal_naive

# Fixed on 2026-11-26, before any model was trained.
BACKTEST = (date(2025, 9, 1), date(2026, 8, 31))
# Held out: used once, for the final model. Do not evaluate on it before then.
FINAL_TEST = (date(2026, 9, 1), date(2026, 11, 25))

MODELS = {"seasonal_naive": seasonal_naive}
WEEKDAYS = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]


def markdown_table(table: pd.DataFrame, label: str, names: dict | None = None) -> str:
    lines = [f"| {label} | Hours | MAE (MW) | MAPE (%) |", "|---|---|---|---|"]
    for key, row in table.iterrows():
        name = names.get(key, key) if names else key
        lines.append(
            f"| {name} | {int(row['hours']):,} | {row['mae_mw']:,.0f} | {row['mape_pct']:.2f} |"
        )
    return "\n".join(lines)


def report(demand: pd.Series) -> str:
    first, last = BACKTEST
    parts = [
        "# Evaluation",
        "",
        "Generated by `python -m forecast.evaluate`. Do not edit by hand.",
        "",
        f"Backtest: every day from {first} to {last}, forecast issued at 10:00 Europe/Madrid on",
        f"the day before. The period {FINAL_TEST[0]} to {FINAL_TEST[1]} is held out and has not",
        "been evaluated. The 2025-04-28 blackout is outside both periods.",
    ]
    for name, model in MODELS.items():
        results = run_backtest(demand, model, first, last)
        total = summarize(results)
        parts += [
            "",
            f"## {name}",
            "",
            f"**MAPE {total['mape_pct']:.2f}%, MAE {total['mae_mw']:,.0f} MW** over "
            f"{total['hours']:,} hours ({total['skipped']} skipped for missing data).",
            "",
            markdown_table(breakdown(results, "month"), "Month"),
            "",
            markdown_table(
                breakdown(results, "weekday"), "Weekday", dict(enumerate(WEEKDAYS))
            ),
            "",
            markdown_table(
                breakdown(results, "holiday"),
                "National holiday",
                {False: "No", True: "Yes"},
            ),
            "",
            markdown_table(breakdown(results, "hour"), "Local hour"),
        ]
    return "\n".join(parts) + "\n"


def main() -> None:
    demand = pd.read_parquet("data/demand.parquet")["demand_mw"]
    text = report(demand)
    Path("docs/evaluation.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
